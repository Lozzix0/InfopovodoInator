'use strict';
/* БАЗА ИНФОПОВОДОВ.
   Тема (группа) — набор логически связанных новостей. Поля новости:
     id   — уникальный идентификатор
     v    — 1: достоверно, 0: ложь
     t    — сам инфоповод (одно предложение, оно же «вырезка»)
     why  — разбор на планёрке: почему это правда или ложь
     src  — источник (для «Википедия: …» ссылка строится автоматически)
     ok   — ВЕРНАЯ подсказка (её доставляют надёжные каналы: босс, серьёзные газеты, архивист)
     bad  — ВВОДЯЩАЯ в заблуждение подсказка (её доставляют ненадёжные каналы: слухи, жёлтая пресса, болтливый друг)
     obv  — очевидная нелепица: подсказка не обязательна
   Новости из реальной жизни проверены источниками; ложь и знаменитости — пародийные. */

function mkItems(group, rows) {
  return rows.map((r, i) => Object.assign({ g: group }, r, { id: group + (i + 1) }));
}

